"""An outside agent's approval at the current head merges the PR, behind four safeguards."""

from __future__ import annotations

import importlib.util
from pathlib import Path
from typing import Any

import factory_outside_approval as outside
import factory_review_policy as policy
import pytest
from pytest import MonkeyPatch

ROOT = Path(__file__).resolve().parents[1]
HEAD = "e644b292d35b9af9480dda648cfa54a73f6b7a91"
OLD = "1a3ba212b96c25adb377ff5fef6cdc5b78ec6b08"
OWNER = {"login": "acme", "type": "User"}
SONNET = "Model: Sonnet 5.5 (claude-sonnet-5-5)"
PR = 42


def verdict(word: str, head: str = HEAD, model: str = SONNET) -> dict[str, Any]:
    return {
        "user": OWNER,
        "author_association": "OWNER",
        "created_at": "2026-11-25T18:00:00Z",
        "html_url": f"https://github.com/acme/widgets/pull/{PR}#issuecomment-9",
        "body": f"Reviewed head `{head[:12]}`: all criteria met, CI green.\n\n{model}\n"
        f"Verdict: {word}\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_",
    }


def review(state: str, body: str, *, commit: str = HEAD, login: str = "acme") -> dict[str, Any]:
    return {
        "user": {"login": login, "type": "User"},
        "author_association": "OWNER" if login == "acme" else "NONE",
        "state": state,
        "commit_id": commit,
        "submitted_at": "2026-11-25T17:00:00Z",
        "html_url": f"https://github.com/acme/widgets/pull/{PR}#pullrequestreview-1",
        "body": body,
    }


def bot(body: str) -> dict[str, Any]:
    return {"user": {"login": "github-actions[bot]", "type": "Bot"}, "body": body}


def fetcher(
    *,
    reviews: list[dict[str, Any]] | None = None,
    comments: list[dict[str, Any]] | None = None,
    commit_message: str = "feat: native roll gate\n\nModel: gpt-5.5",
    head: str = HEAD,
) -> outside.Fetch:
    pages = {
        f"pulls/{PR}": {
            "state": "open",
            "draft": False,
            "head": {"sha": head},
            "base": {"ref": "main"},
        },
        f"pulls/{PR}/reviews": reviews or [],
        f"issues/{PR}/comments": comments or [],
        f"pulls/{PR}/commits": [{"sha": head, "commit": {"message": commit_message}}],
        f"commits/{head}": {
            "sha": head,
            "parents": [{"sha": OLD}],
            "commit": {"message": commit_message},
        },
    }

    def read(path: str) -> object:
        key = path.split("?", 1)[0]
        if "page=" in path and not path.endswith("page=1"):
            return []
        return pages.get(key)

    return read


def check(**kwargs: Any) -> outside.Approval:
    return outside.evaluate(fetcher(**kwargs), PR, owner="acme")


def test_a_verdict_approve_at_the_head_by_an_independent_model_authorizes() -> None:
    found = check(comments=[verdict("approve")])
    assert found.approved, found.reason
    assert found.model == "Sonnet 5.5 (claude-sonnet-5-5)"
    assert found.url.endswith("#issuecomment-9")


def test_a_formal_approved_review_with_a_model_line_authorizes() -> None:
    assert check(reviews=[review("APPROVED", f"Looks right.\n{SONNET}")]).approved
    assert not check(reviews=[review("APPROVED", "Looks right.")]).approved


def test_an_approval_on_an_older_head_does_not_authorize() -> None:
    assert not check(comments=[verdict("approve", head=OLD)]).approved
    assert not check(reviews=[review("APPROVED", SONNET, commit=OLD)]).approved


@pytest.mark.parametrize(
    "message",
    ["fix\n\nModel: claude-sonnet-5-5", "fix\n\nModel: anthropic/claude-sonnet-5-5"],
)
def test_the_model_of_any_pr_commit_cannot_approve(message: str) -> None:
    found = check(comments=[verdict("approve")], commit_message=message)
    assert not found.approved
    assert "authored this PR" in found.reason


def test_the_recorded_head_author_cannot_approve() -> None:
    marker = policy.agent_model_author_marker(
        pr=PR, head=HEAD, model="claude-sonnet-5-5", agent="7"
    )
    found = check(comments=[verdict("approve"), bot(marker)], commit_message="fix: no trailer")
    assert not found.approved
    assert "authored this PR" in found.reason


@pytest.mark.parametrize(
    ("reviews", "comments"),
    [
        ([review("CHANGES_REQUESTED", "Fix it.", login="other")], []),
        ([], [verdict("changes-requested", model="Model: gpt-5.4")]),
        (
            [],
            [
                bot(
                    f"<!-- {policy.MARKER_PREFIX}-factory-semantic-review-v1:pr-{PR}:head-{HEAD}"
                    ":reviewer-12:producer-unknown:verdict-repair -->"
                )
            ],
        ),
    ],
)
def test_a_change_request_on_the_same_head_blocks_the_approval(
    reviews: list[dict[str, Any]], comments: list[dict[str, Any]]
) -> None:
    found = check(reviews=reviews, comments=[*comments, verdict("approve")])
    assert not found.approved
    assert "changes" in found.reason or "repair" in found.reason


def test_a_change_request_on_an_older_head_does_not_block() -> None:
    old = review("CHANGES_REQUESTED", "Fix it.", commit=OLD, login="other")
    assert check(reviews=[old], comments=[verdict("approve")]).approved


def load_controller() -> Any:
    spec = importlib.util.spec_from_file_location(
        "outside_approval_controller", ROOT / ".github/scripts/factory-review-controller.py"
    )
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def test_failing_required_checks_still_hold_an_outside_approval(monkeypatch: MonkeyPatch) -> None:
    ctrl = load_controller()
    passing = {"decision": "pass", "reason": "ok"}
    monkeypatch.setattr(ctrl, "poll_mergeable_gate", lambda *_a: passing)
    monkeypatch.setattr(
        ctrl, "required_checks_gate", lambda *_a: {"decision": "retry", "reason": "CI pending"}
    )
    monkeypatch.setattr(ctrl._outside_approval, "authorization", lambda *_a, **_k: {"model": "x"})
    assert ctrl.mechanical_merge_gate(PR, HEAD)["decision"] == "retry"


def test_authorize_ready_records_and_returns_the_outside_approval(monkeypatch: MonkeyPatch) -> None:
    ctrl = load_controller()
    pr = {
        "state": "OPEN",
        "headRefOid": HEAD,
        "headRefName": "feature/rust-roll",
        "body": "Closes #5678.",
        "labels": [{"name": "factory"}, {"name": "factory:ready"}],
    }
    monkeypatch.setattr(ctrl, "pr_json", lambda _n: pr)
    monkeypatch.setattr(ctrl, "outside_claim", lambda *_a: None)
    monkeypatch.setattr(ctrl, "review_comment_bodies", lambda _n: [])
    monkeypatch.setattr(ctrl, "model_comment_bodies", lambda _n: [])
    recorded: list[tuple[int, str]] = []
    monkeypatch.setattr(
        outside, "record", lambda _repo, number, approval: recorded.append((number, approval.head))
    )
    monkeypatch.setattr(ctrl._outside_approval, "record", outside.record)
    monkeypatch.setattr(ctrl, "repo_fetch", fetcher(comments=[verdict("approve")]))
    result = ctrl.authorize_ready(PR)
    assert result["authorized"] is True
    assert result["outside_approval"]["model"] == "Sonnet 5.5 (claude-sonnet-5-5)"
    assert recorded == [(PR, HEAD)]


def test_promote_moves_an_approved_review_pr_to_ready(monkeypatch: MonkeyPatch) -> None:
    base = fetcher(comments=[verdict("approve")])
    labels = [{"name": name} for name in ("factory", "factory:review", "factory:unowned", "bug")]

    def read(path: str) -> object:
        return {"labels": labels} if path == f"issues/{PR}" else base(path)

    writes: list[str] = []
    monkeypatch.setattr(
        outside.subprocess, "run", lambda *_a, **kwargs: writes.append(kwargs["input"])
    )
    result = outside.promote("acme/widgets", PR, fetch=read)
    assert result["promoted"] is True
    assert writes and '"factory:ready"' in writes[0] and '"factory:review"' not in writes[0]
    assert '"bug"' in writes[0] and '"factory:unowned"' in writes[0]


