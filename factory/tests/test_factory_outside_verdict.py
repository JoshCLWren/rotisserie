"""An outside agent's comment-review verdict reaches the repair worker's findings file."""

from __future__ import annotations

import json
import os
import stat
import subprocess
from pathlib import Path

import factory_outside_verdict as outside

ROOT = Path(__file__).resolve().parents[1]
HELPER = ROOT / ".github/scripts/factory-review-findings.sh"
HEAD = "e644b292d35b9af9480dda648cfa54a73f6b7a91"
OLD = "1a3ba212b96c25adb377ff5fef6cdc5b78ec6b08"
OWNER = {"login": "acme", "type": "User"}
MODEL = "Model: Sonnet 5.5 (claude-sonnet-5-5)"
FOOTER = "---\n_Generated by [Claude Code](https://claude.ai/code)_"


def summary(verdict: str, head: str = HEAD) -> str:
    return (
        f"Outside review summary for head `{head[:12]}`: 4 ruff errors in the new test.\n\n"
        f"{MODEL}\nVerdict: {verdict}\n\n{FOOTER}"
    )


def review(body: str, commit: str = HEAD) -> dict[str, object]:
    return {
        "user": OWNER,
        "author_association": "OWNER",
        "state": "COMMENTED",
        "commit_id": commit,
        "submitted_at": "2026-11-25T17:22:27Z",
        "body": body,
        "html_url": "https://github.com/acme/widgets/pull/42#pullrequestreview-1",
    }


def comment(body: str) -> dict[str, object]:
    return {
        "user": OWNER,
        "author_association": "OWNER",
        "created_at": "2026-11-25T17:22:29Z",
        "body": body,
        "html_url": "https://github.com/acme/widgets/pull/42#issuecomment-1",
    }


def found(reviews: list[dict[str, object]], comments: list[dict[str, object]]) -> str:
    hit = outside.latest(reviews, comments, head=HEAD, owner="acme", marker_prefix="widgets")
    return outside.findings_section(hit)


def test_verdict_rule_matches_the_last_line_outside_fences() -> None:
    assert outside.verdict_of(summary("changes-requested")) == "changes-requested"
    assert outside.verdict_of(f"{MODEL}\n```\nVerdict: changes-requested\n```") is None
    assert outside.verdict_of(f"{MODEL}\n> Verdict: approve") is None
    assert outside.verdict_of("Verdict: approve") is None


def test_changes_requested_at_head_becomes_findings() -> None:
    text = found([], [comment(summary("changes-requested"))])
    assert "Outside agent review: changes requested" in text
    assert "4 ruff errors" in text


def test_old_head_approve_and_fenced_verdicts_add_no_findings() -> None:
    assert found([review(summary("changes-requested", OLD), OLD)], []) == ""
    assert found([], [comment(summary("changes-requested", OLD))]) == ""
    assert found([review(summary("approve"))], []) == ""
    fenced = f"Head {HEAD[:12]}.\n{MODEL}\n```text\nVerdict: changes-requested\n```"
    assert found([review(fenced)], [comment(fenced)]) == ""


def test_bot_and_factory_marker_comments_are_ignored() -> None:
    bot = {**comment(summary("changes-requested")), "user": {"login": "x[bot]", "type": "Bot"}}
    marked = comment(
        f"<!-- widgets-factory-review-v2:{HEAD}:pass -->\n" + summary("changes-requested")
    )
    assert found([], [bot, marked]) == ""


def test_findings_file_carries_the_outside_summary(tmp_path: Path) -> None:
    data = tmp_path / "fake"
    data.mkdir()
    (data / "reviews").write_text(json.dumps([review("Line comments below.\n" + MODEL)]))
    (data / "comments").write_text(json.dumps([comment(summary("changes-requested"))]))
    threads = {"data": {"repository": {"pullRequest": {"reviewThreads": {
        "pageInfo": {"hasNextPage": False, "endCursor": None}, "nodes": []}}}}}  # fmt: skip
    (data / "threads").write_text(json.dumps(threads))
    bin_dir = tmp_path / "bin"
    bin_dir.mkdir()
    gh = bin_dir / "gh"
    gh.write_text(f"""#!/usr/bin/env bash
case "$*" in
  *graphql*) cat {data}/threads ;;
  *pulls/*/reviews*) cat {data}/reviews ;;
  *issues/*/comments*) cat {data}/comments ;;
  *check-runs*) echo '{{"check_runs":[]}}' ;;
  "pr view"*) printf '' ;;
  *) exit 1 ;;
esac
""")
    gh.chmod(gh.stat().st_mode | stat.S_IEXEC)
    out = tmp_path / "findings.md"
    result = subprocess.run(
        [
            "bash",
            "-c",
            f"set -Eeuo pipefail; source {HELPER}; factory_collect_review_findings 42 {HEAD} {out}",
        ],
        cwd=ROOT,
        text=True,
        capture_output=True,
        check=False,
        env={**os.environ, "PATH": f"{bin_dir}{os.pathsep}{os.environ['PATH']}"},
    )
    assert result.returncode == 0, result.stderr
    text = out.read_text()
    assert "# Review findings for PR #42" in text
    assert "Outside agent review: changes requested" in text
    assert "4 ruff errors in the new test" in text
